import sys,json
from pathlib import Path
sys.path.insert(0,'python')
from deda.simulator import simulate
out=Path('wokwi/sketch')
cases=[('Horn behind',{}),('Siren left',dict(sound='siren',angle=270)),('Direction unavailable',dict(condition='dropout')),('Uncertain class',dict(confidence=.30)),('Ambient only',dict(sound='ambient'))]
lines=['// Generated by ../generate_scenarios.py; synthetic inputs, not recordings.','#pragma once','#include "deda.h"','typedef struct { const char *name; const deda_window_t *windows; unsigned count; float onset_ms; } Scenario;']
manifest=[]
def f(x): return format(float(x),'.9g')+('f' if '.' in format(float(x),'.9g') or 'e' in format(float(x),'.9g') else '.0f')
for i,(name,opts) in enumerate(cases):
 r=simulate(opts)
 lines.append(f'static const deda_window_t windows_{i}[] = {{')
 for w in r['frames']:
  d=w['direction']
  lines.append('{'+f(w['t_ms'])+', {'+','.join(map(f,w['probs']))+'}, '+str(int(w['direction_available']))+', {'+','.join(f(d[k]) for k in ['theta_deg','closure','norm','coherence'])+'}},')
 lines.append('};')
 manifest.append(dict(name=name,options=r['options'],onset_ms=r['onset_ms'],alerts=r['alerts']))
lines.append('static const Scenario scenarios[] = {')
for i,m in enumerate(manifest): lines.append('{"'+m['name']+'", windows_'+str(i)+', sizeof(windows_'+str(i)+')/sizeof(windows_'+str(i)+'[0]), '+f(m['onset_ms'])+'},')
lines.extend(['};','static const unsigned SCENARIO_COUNT = sizeof(scenarios)/sizeof(scenarios[0]);'])
(out/'scenario_data.h').write_text('\n'.join(lines)+'\n')
Path('wokwi/expected_results.json').write_text(json.dumps(manifest,indent=2))
exec(Path('wokwi/build_diagram.py').read_text())
print([(m['name'],m['alerts']) for m in manifest])
